export function getAllMilestones() {
  return [...JOURNEY_MILESTONES, ...LONG_TERM_MILESTONES];
}

export function getCurrentMilestone(currentDay) {
  const all = getAllMilestones();
  for (const phase of all) {
    const [start, end] = phase.days.split('-').map(Number);
    if (currentDay >= start && currentDay <= end) return phase;
  }
  return null;
}

